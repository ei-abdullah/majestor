    ADD COLUMN accepted_at TIMESTAMP WITHOUT TIME ZONE;

CREATE TABLE carpool_messages
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    sender_name     VARCHAR(255)                            NOT NULL,
    sender_username VARCHAR(255),
    receiver_name   VARCHAR(255)                            NOT NULL,
    booking_id      BIGINT,
    message         TEXT                                    NOT NULL,
    date            VARCHAR(255),
    message_status  VARCHAR(50),
    created_at      TIMESTAMP WITHOUT TIME ZONE             NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_carpool_messages PRIMARY KEY (id)
);

CREATE INDEX idx_carpool_messages_participants ON carpool_messages (sender_name, receiver_name, created_at);
CREATE INDEX idx_carpool_messages_booking_id ON carpool_messages (booking_id);
